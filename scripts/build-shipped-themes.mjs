#!/usr/bin/env node
// @ts-check
/**
 * Writes the shipped respondent themes the admin's Appearance drawer offers. The admin runs no
 * kernel code (R2), so the palettes are derived here and landed as data;
 * `apps/admin/lib/forms/shipped-themes.test.ts` re-derives them and fails on drift.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { deriveAppearance } from "../packages/core/dist/index.js";

const OUT = fileURLToPath(new URL("../apps/admin/lib/forms/shipped-themes.ts", import.meta.url));

/** Each theme's accents in `packages/ui/src/theme.css`, light mode. */
export const SHIPPED_ACCENTS = {
  slate: { primary: "#2c6e63", secondary: "#4f5b70" },
  harbor: { primary: "#1f5eb8", secondary: "#4a5a75" },
  sand: { primary: "#a24e2c", secondary: "#6d6152" },
  plum: { primary: "#6d28a8", secondary: "#5f5470" },
};

const HEADER = `/* Generated by scripts/build-shipped-themes.mjs. The admin runs no kernel code (R2), so the
   palettes are landed as data; shipped-themes.test.ts re-derives them and fails on drift. */

export interface ShippedTheme {
  readonly key: string;
  readonly accents: { readonly primary: string; readonly secondary: string };
  readonly face: string;
  readonly palettes: Record<string, Record<string, string>>;
}

export const SHIPPED_THEMES: readonly ShippedTheme[] = `;

function build() {
  return Object.entries(SHIPPED_ACCENTS).map(([key, accents]) => {
    const derived = deriveAppearance(accents);
    return { key, accents, face: derived.face, palettes: derived.palettes };
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, `${HEADER}${JSON.stringify(build(), null, 2)};\n`);
  console.log(`build-shipped-themes: wrote ${OUT}`);
}

export { build };
